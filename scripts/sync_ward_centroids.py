#!/usr/bin/env python3
"""Give the console the ward centroids the app already has.

## Why this exists

A report that arrives over USSD has no GPS. It cannot: USSD rides the signalling
channel and has no access to the handset's location. What it has is the ward the
caller chose on a menu.

`LiveMap` skips any alert whose lat/lng are not finite — correctly, because the
alternative is the C-5 defect this codebase already fixed once, where a missing
fix fell back to central Jos and an alert with no location rendered as a
confident pin. So a USSD emergency appeared in the incident list and NOWHERE ON
THE MAP the operator is actually watching.

The app resolves a ward from `assets/geo/plateau_wards.json` — 207 real INEC
wards with centroids. The console had no access to it at all. This copies it
across so an approximate location can be drawn as an APPROXIMATE location.

## The radius is computed, not guessed

Drawing a 5km circle on every ward would be a number somebody made up. A ward in
Jos North is a few streets; a ward in Wase is a large piece of countryside, and a
circle that flatters the small ones lies about the big ones.

So each ward's radius is half the distance to the nearest OTHER ward centroid in
the same LGA — the largest circle that does not overlap its neighbour, which is a
defensible reading of "somewhere in this ward" from centroid data alone. Clamped
at both ends: never below 800m, because no centroid is that good, and never above
25km, because beyond that the circle stops being information.

Run with --check in CI to fail on drift.
"""

import argparse
import json
import math
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ASSET = REPO / 'assets' / 'geo' / 'plateau_wards.json'
OUT = REPO / 'hq-dashboard-next' / 'src' / 'lib' / 'ward_centroids.ts'

MIN_RADIUS_M = 800
MAX_RADIUS_M = 25_000
# Used when an LGA has exactly one ward in the data, so there is no neighbour to
# measure against. The median of everything else would be circular; this is the
# midpoint of the clamp, chosen openly rather than derived from nothing.
LONE_WARD_RADIUS_M = 8_000


def metres_between(a, b):
    """Great-circle distance in metres. Haversine: Plateau spans ~2 degrees, so a
    flat approximation would be off by enough to matter at the 1km scale these
    radii are quoted at."""
    r = 6_371_000
    p1, p2 = math.radians(a['lat']), math.radians(b['lat'])
    dp = p2 - p1
    dl = math.radians(b['lng'] - a['lng'])
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(h))


def build():
    wards = json.loads(ASSET.read_text())['wards']
    by_lga = {}
    for w in wards:
        by_lga.setdefault(w['lga'], []).append(w)

    out = []
    for w in wards:
        siblings = [s for s in by_lga[w['lga']] if s is not w]
        if siblings:
            nearest = min(metres_between(w, s) for s in siblings)
            radius = int(max(MIN_RADIUS_M, min(MAX_RADIUS_M, nearest / 2)))
        else:
            radius = LONE_WARD_RADIUS_M
        out.append({
            'lga': w['lga'],
            'ward': w['ward'],
            'lat': round(w['lat'], 6),
            'lng': round(w['lng'], 6),
            'radiusM': radius,
        })
    return out


HEADER = '''/**
 * Ward centroids, with an honest radius for each.
 *
 * GENERATED by scripts/sync_ward_centroids.py from assets/geo/plateau_wards.json.
 * Do not edit by hand — CI fails on drift. The app's asset is the single source
 * of truth, because it is what resolves an incident's ward in the first place.
 *
 * ## What this is for
 *
 * A report that arrives over USSD has no GPS and cannot have one: USSD rides the
 * signalling channel with no access to the handset's location. What it has is the
 * ward the caller chose on a menu.
 *
 * `LiveMap` skips any alert without finite coordinates, correctly — the
 * alternative is the C-5 defect where a missing fix fell back to central Jos and
 * an unlocated alert drew a confident pin. So these centroids exist to draw an
 * approximate location AS an approximate location: an area, never a pin.
 *
 * ## The radius
 *
 * Half the distance to the nearest other ward centroid in the same LGA — the
 * largest circle that does not overlap its neighbour. Clamped to [800m, 25km]:
 * no centroid is better than 800m, and past 25km a circle stops being
 * information. A ward in Jos North is a few streets and one in Wase is a large
 * piece of countryside; a single made-up radius would flatter the first and lie
 * about the second.
 */

export interface WardCentroid {
  lga: string;
  ward: string;
  lat: number;
  lng: number;
  /** Radius in metres of the area this centroid stands for. See the note above. */
  radiusM: number;
}

export const wardCentroids: WardCentroid[] = '''


def render(rows):
    return HEADER + json.dumps(rows, indent=2, ensure_ascii=False) + ';\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true',
                    help='fail if the generated file is out of date')
    args = ap.parse_args()

    if not ASSET.exists():
        print(f'✗ {ASSET.relative_to(REPO)} is missing', file=sys.stderr)
        return 1

    rows = build()
    if len(rows) != 207:
        # The count is asserted because a truncated asset would silently shrink
        # the map's coverage, and the wards that vanished would be the ones whose
        # incidents stop appearing.
        print(f'✗ built {len(rows)} wards, expected 207', file=sys.stderr)
        return 1

    wanted = render(rows)
    if args.check:
        if not OUT.exists() or OUT.read_text() != wanted:
            print('✗ ward_centroids.ts is out of date with assets/geo/plateau_wards.json.',
                  file=sys.stderr)
            print('  Run: python3 scripts/sync_ward_centroids.py', file=sys.stderr)
            return 1
        print(f'✓ the console has all {len(rows)} ward centroids')
        return 0

    OUT.write_text(wanted)
    radii = sorted(r['radiusM'] for r in rows)
    print(f'✓ wrote {OUT.relative_to(REPO)}: {len(rows)} wards')
    print(f'  radius: min {radii[0]}m, median {radii[len(radii) // 2]}m, max {radii[-1]}m')
    return 0


if __name__ == '__main__':
    sys.exit(main())
