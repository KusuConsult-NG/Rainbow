#!/usr/bin/env python3
"""Generate the "is this geography real?" diagnostic from the ward asset.

    python3 scripts/sync_geography_inventory.py            # write the .sql
    python3 scripts/sync_geography_inventory.py --check     # fail if it drifted

Section 4 of `why_is_the_board_empty.sql` lists the geographies incidents are
filed under, and ends:

    -- Cross-check these names with: python3 scripts/sync_tactical_map.py --check

That script compares the REPOSITORY's tactical map against the ward asset. It
cannot see production's rows, so the actual cross-check — is this LGA/ward pair
one of the 207 real ones? — was left to an operator reading a list by eye. They
did it, and found `JOS SOUTH / BUKURU` and `JOS SOUTH / BUKURU WARD` filed as
different places, and `BUKURU WARD` recorded under six different LGAs when
`BUKURU` is a ward of Jos South and of nowhere else.

Doing that by eye against 207 names is not a check anybody should have to
perform. So the inventory is EXTRACTED and embedded in one read-only statement,
the same way `which_migrations_are_applied.sql` carries the object inventory:
the database then answers the question itself, per row, with the count of
incidents or postings behind each bad name.

And it says what was probably meant. Because a ward name is unique to its LGA in
almost every case, "BUKURU is a ward of JOS SOUTH" is usually the whole answer.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ASSET = REPO / 'assets' / 'geo' / 'plateau_wards.json'
OUT = REPO / 'scripts' / 'which_geography_is_real.sql'


def lit(text: str) -> str:
    """A SQL string literal. Ward names contain apostrophes — GYEL 'A'."""
    return "'" + text.replace("'", "''") + "'"


def wards() -> list[tuple[str, str]]:
    data = json.loads(ASSET.read_text(encoding='utf-8'))
    rows = data.get('wards')
    if not isinstance(rows, list) or not rows:
        raise SystemExit(f'✗ {ASSET.relative_to(REPO)} has no `wards` list')
    pairs = sorted({(str(w['lga']).strip(), str(w['ward']).strip())
                    for w in rows})
    declared = data.get('count')
    if isinstance(declared, int) and declared != len(rows):
        raise SystemExit(
            f'✗ {ASSET.relative_to(REPO)} says count={declared} and holds '
            f'{len(rows)} wards. The diagnostic would be built from a list '
            f'that the asset itself disagrees with.')
    return pairs


HEADER = '''\
-- ============================================================================
-- Is this geography real?
--
-- READ-ONLY. Safe on production. ONE statement, because the Supabase SQL editor
-- shows only the last result set of a multi-statement run.
--
-- GENERATED by scripts/sync_geography_inventory.py from
-- assets/geo/plateau_wards.json — do not edit by hand. CI fails if it drifts.
--
-- ## What this answers
--
-- `alert_in_my_area()` decides whether a staff account sees an incident by
-- comparing the incident's LGA and ward with the account's posting, through
-- `geo_key()`. If either name is not a real place, or is a real ward recorded
-- under the wrong LGA, the comparison cannot match and that officer's board is
-- empty while the rows sit right there.
--
-- The console's ward and polling-unit filters come from the tactical map, so a
-- row whose ward is not in it can be FILED but not FILTERED.
--
-- This lists every LGA/ward pair that incidents or staff postings actually
-- carry, says whether it is one of the {n} surveyed wards of Plateau State,
-- and when it is not, says what was probably meant.
--
-- ## How names are compared
--
-- Through `public.geo_key()`, so this diagnostic agrees with the RLS that
-- decides who sees what. That matters for reading the output: if
-- `20261031000000_a_ward_is_not_called_ward.sql` has NOT been applied here,
-- `geo_key` does not drop a trailing WARD, and every `X WARD` row below will be
-- reported as not a real place — which is exactly the state those rows are in
-- on such a database, and applying that migration is the fix.
--
-- If this fails with
--
--   function public.geo_key(text) does not exist
--       20261009000000_ward_names_compared_by_key.sql
--
-- apply that migration first.
-- ============================================================================

WITH known(lga, ward) AS (VALUES
{values}
),
-- Every geography the live database actually uses, with how much is behind it.
-- Staff only for postings: a citizen's geo_* is not a posting and is not
-- compared to anything.
live(kind, lga, ward, rows) AS (
  SELECT 'incident', a.geo_lga, a.geo_ward, count(*)
    FROM public.alerts a
   GROUP BY a.geo_lga, a.geo_ward
  UNION ALL
  SELECT 'posting', p.geo_lga, p.geo_ward, count(*)
    FROM public.profiles p
   WHERE upper(coalesce(p.role, '')) NOT IN ('CITIZEN', 'USER')
   GROUP BY p.geo_lga, p.geo_ward
),
judged AS (
  SELECT l.kind, l.lga, l.ward, l.rows,
         EXISTS (SELECT 1 FROM known k
                  WHERE public.geo_key(k.lga)  = public.geo_key(l.lga)
                    AND public.geo_key(k.ward) = public.geo_key(l.ward))
           AS pair_is_real,
         EXISTS (SELECT 1 FROM known k
                  WHERE public.geo_key(k.lga) = public.geo_key(l.lga))
           AS lga_is_real,
         -- Which LGA(s) DO have a ward by this name. For the six-LGA
         -- `BUKURU WARD` this one column is the whole answer.
         (SELECT string_agg(DISTINCT k.lga, ', ' ORDER BY k.lga) FROM known k
           WHERE public.geo_key(k.ward) = public.geo_key(l.ward))
           AS ward_belongs_to
    FROM live l
)
SELECT 1 AS ord, 'summary' AS section,
       format('%s of %s geographies in use are real',
              count(*) FILTER (WHERE pair_is_real), count(*)) AS name,
       CASE WHEN count(*) FILTER (WHERE NOT pair_is_real) = 0
            THEN 'every LGA/ward pair on this database is one of the {n} surveyed wards'
            ELSE format('%s pair(s) are not, covering %s incident(s) and %s posting(s) — read the rows below',
                        count(*) FILTER (WHERE NOT pair_is_real),
                        coalesce(sum(rows) FILTER (WHERE NOT pair_is_real AND kind = 'incident'), 0),
                        coalesce(sum(rows) FILTER (WHERE NOT pair_is_real AND kind = 'posting'), 0))
       END AS detail
  FROM judged
UNION ALL
-- A posting first: an unreal posting blinds an officer to everything, while an
-- unreal incident hides one incident from everybody.
SELECT 2, 'posting is not a real place',
       format('%s / %s', coalesce(nullif(lga, ''), '(blank)'),
              coalesce(nullif(ward, ''), '(blank)')),
       format('%s staff account(s). %s', rows,
         CASE
           WHEN nullif(trim(coalesce(lga, '')), '') IS NULL
             THEN 'No LGA recorded. A blank posting is the WEAKEST scope, not the widest, so this account sees nothing it is not assigned.'
           WHEN NOT lga_is_real
             THEN 'No such LGA in Plateau State. Nothing can match it.'
           WHEN nullif(trim(coalesce(ward, '')), '') IS NULL
             THEN 'No ward recorded. This account matches at LGA level only.'
           WHEN ward_belongs_to IS NOT NULL
             THEN format('That ward belongs to %s, not to this LGA. Either the LGA or the ward is wrong.', ward_belongs_to)
           ELSE 'That ward is in no LGA of Plateau State. Probably a spelling the tactical map does not have.'
         END)
  FROM judged WHERE kind = 'posting' AND NOT pair_is_real
UNION ALL
SELECT 3, 'incident is not at a real place',
       format('%s / %s', coalesce(nullif(lga, ''), '(blank)'),
              coalesce(nullif(ward, ''), '(blank)')),
       format('%s incident(s). %s', rows,
         CASE
           WHEN nullif(trim(coalesce(lga, '')), '') IS NULL
             THEN 'No LGA recorded. Only HQ sees this, by design — an unlocated incident must not be scoped away to nobody.'
           WHEN NOT lga_is_real
             THEN 'No such LGA in Plateau State. No LGA or ward officer can match it.'
           WHEN nullif(trim(coalesce(ward, '')), '') IS NULL
             THEN 'No ward recorded. LGA officers see it; ward and unit officers cannot.'
           WHEN ward_belongs_to IS NOT NULL
             THEN format('That ward belongs to %s, not to this LGA. Either the LGA or the ward is wrong.', ward_belongs_to)
           ELSE 'That ward is in no LGA of Plateau State. It can be filed but not filtered.'
         END)
  FROM judged WHERE kind = 'incident' AND NOT pair_is_real
UNION ALL
SELECT 4, 'in use and real', format('%s / %s', lga, ward),
       format('%s %s(s)', rows, kind)
  FROM judged WHERE pair_is_real
 ORDER BY ord, name;
'''


def render(pairs: list[tuple[str, str]]) -> str:
    values = ',\n'.join(f'  ({lit(lga)}, {lit(ward)})' for lga, ward in pairs)
    return HEADER.format(values=values, n=len(pairs))


def main() -> int:
    pairs = wards()
    want = render(pairs)
    lgas = len({p[0] for p in pairs})
    counts = f'{len(pairs)} wards across {lgas} LGAs'
    if '--check' in sys.argv:
        have = OUT.read_text(encoding='utf-8') if OUT.exists() else ''
        if have != want:
            print('✗ scripts/which_geography_is_real.sql is out of date.\n'
                  '  Run: python3 scripts/sync_geography_inventory.py',
                  file=sys.stderr)
            return 1
        print(f'✓ the geography inventory matches the asset: {counts}')
        return 0
    OUT.write_text(want, encoding='utf-8')
    print(f'✓ wrote {OUT.relative_to(REPO)}: {counts}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
